import pandas as pd
from pathlib import Path


# ============================================================
# PATHS
# ============================================================

BASE_DIR = Path(__file__).resolve().parent.parent

DATA_DIR = BASE_DIR / "data"

RAW_DIR = DATA_DIR / "raw"
CLEANED_DIR = DATA_DIR / "cleaned"

HISTORICAL_SEM2_DIR = CLEANED_DIR / "historical_sem2"

OUTPUT_DIR = DATA_DIR / "analysis" / "dashboard2"

OUTPUT_DIR.mkdir(parents=True, exist_ok=True)


# ============================================================
# PERFORMANCE SETTINGS
# ============================================================

ASSIGNMENT_MAX_MARKS = 20
TEST_MAX_MARKS = 20

ATTENDANCE_WEIGHT = 0.30
ASSIGNMENT_WEIGHT = 0.30
TEST_WEIGHT = 0.40


# ============================================================
# HELPER FUNCTIONS
# ============================================================

def find_cleaned_file(folder, base_name):
    """
    Finds cleaned CSV using the standard cleaning output name.

    Example:
        assignments.csv
        ->
        assignments_cleaned.csv
    """

    possible_names = [
        f"{base_name}_cleaned.csv",
        f"{base_name}.csv"
    ]

    for name in possible_names:

        path = folder / name

        if path.exists():
            return path

    return None


def load_cleaned_csv(folder, base_name, required=True):
    """
    Load a cleaned dataset.
    """

    path = find_cleaned_file(
        folder,
        base_name
    )

    if path is None:

        if required:

            raise FileNotFoundError(
                f"\nRequired file not found.\n"
                f"Folder: {folder}\n"
                f"Expected: {base_name}_cleaned.csv"
            )

        return pd.DataFrame()

    return pd.read_csv(path)


def load_current_performance():
    """
    Load the current student performance generated by
    performance_analysis.py.
    """

    path = (
        DATA_DIR
        / "analysis"
        / "powerbi"
        / "powerbi_student_performance.csv"
    )

    if not path.exists():

        raise FileNotFoundError(
            f"\nCurrent performance file not found:\n{path}"
        )

    df = pd.read_csv(path)

    required_columns = [
        "Student_ID",
        "Program_ID",
        "Program_Name",
        "Semester_ID",
        "Semester_Name",
        "Attendance_Percentage",
        "Assignment_Percentage",
        "Test_Percentage",
        "Overall_Performance_Score"
    ]

    missing = [
        column
        for column in required_columns
        if column not in df.columns
    ]

    if missing:

        raise ValueError(
            "\nMissing columns in current performance file:\n"
            f"{missing}"
        )

    return df


def get_semester_number(df):
    """
    Derive Semester_Number from Semester_Name.

    Example:
        Semester 1 -> 1
        Semester 3 -> 3

    No Semester_ID mapping is used.
    """

    if "Semester_Number" in df.columns:

        values = pd.to_numeric(
            df["Semester_Number"],
            errors="coerce"
        )

        if values.notna().any():

            return values

    if "Semester_Name" not in df.columns:

        raise ValueError(
            "Semester_Name is required to derive Semester_Number."
        )

    return pd.to_numeric(
        df["Semester_Name"]
        .astype(str)
        .str.extract(r"(\d+)", expand=False),
        errors="coerce"
    )


def normalize_attendance_status(df):
    """
    Standardize attendance status column.
    """

    df = df.copy()

    if df.empty:
        return df

    if "Attendance_Status" not in df.columns:

        if "Status" in df.columns:

            df["Attendance_Status"] = df["Status"]

        else:

            raise ValueError(
                "Attendance_Status/Status column not found."
            )

    df["Attendance_Status"] = (
        df["Attendance_Status"]
        .astype(str)
        .str.strip()
        .str.lower()
    )

    return df


# ============================================================
# CURRENT PERFORMANCE
# ============================================================

def prepare_current_performance():

    print("\nLoading current performance...")

    current = load_current_performance()

    current["Semester_Number"] = get_semester_number(
        current
    )

    current["Semester_Number"] = (
        current["Semester_Number"]
        .astype("Int64")
    )

    # --------------------------------------------------------
    # Keep only valid current semester records
    # --------------------------------------------------------

    current = current[
        current["Semester_Number"].notna()
    ].copy()

    # --------------------------------------------------------
    # Remove accidental duplicate student-semester records
    # --------------------------------------------------------

    current = (
        current
        .drop_duplicates(
            subset=[
                "Student_ID",
                "Semester_ID"
            ]
        )
        .copy()
    )

    print(
        f"Current performance records: {len(current)}"
    )

    return current


